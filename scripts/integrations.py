#!/usr/bin/env python3
"""Generates what the launcher integrations share with Safay (docs/ARCHITECTURE.md, Launcher integration):

- `integrations/raycast/src/generated.ts`: the bridge AppleScript and the launcher text (English: the Raycast Store
  takes no custom localization) for the Raycast / Tinycast extension (committed, so the extension builds on its own);
- `--alfred OUT`: `Safay.alfredworkflow`, built deterministically from `integrations/alfred/` (and `alfred_info` here) with
  the same script and text (scripts/package.py puts it in the app).

The text comes only from `locales/` (English is the key unless `en.json` says otherwise), so the launchers say what Safay
says. `--check` fails when generated.ts is out of date.
"""
import argparse
import json
import plistlib
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BRIDGE = ROOT / "integrations/shared/safay.applescript"
GENERATED = ROOT / "integrations/raycast/src/generated.ts"
LANGUAGES = {"en": "en.json", "zh-Hans": "zh-Hans.json", "zh-Hant": "zh-Hant.json"}
# Every text a launcher shows; each is a key of Safay's own tables.
KEYS = {
    "search": "Search accounts",
    "disabledTitle": "Third-party plugin interface is off",
    "disabledSubtitle": "Turn it on in Safay’s Settings → Advanced",
    "permissionTitle": "Safay automation access is off",
    "permissionSubtitle": "Allow this app to control Safay in System Settings → Automation",
    "notRunningTitle": "Safay isn’t running",
    "notReadyTitle": "Unlock Safay first",
    "notReadySubtitle": "Search works once you unlock Safay after it starts",
    "noMatches": "No matching accounts",
    "copy": "Copy Code",
    "openSafay": "Open Safay",
    "openSettings": "Open System Settings",
    "failed": "Couldn’t copy the code",
    "busy": "Safay is busy with another request",
    "notFound": "This account is no longer in Safay",
}


def strings() -> dict:
    tables = {code: json.loads((ROOT / "locales" / name).read_text(encoding="utf-8")) for code, name in LANGUAGES.items()}
    out = {}
    for code, table in tables.items():
        missing = [k for k in KEYS.values() if code != "en" and k not in table]
        if missing:
            sys.exit(f"locales/{LANGUAGES[code]} lacks {missing}")
        out[code] = {name: table.get(key, key) for name, key in KEYS.items()}
    return out


def generated_ts() -> str:
    # The Raycast Store takes US English only and no custom localization, so the extension gets Safay's English text;
    # the Alfred workflow keeps all three languages.
    return (
        "// Generated by scripts/integrations.py from integrations/shared/safay.applescript and locales/en.json. Do not edit.\n\n"
        f"export const BRIDGE = {json.dumps(BRIDGE.read_text(encoding='utf-8'))};\n\n"
        f"export const TEXT = {json.dumps(strings()['en'], indent=2)} as const;\n"
    )


def alfred_info() -> dict:
    """The workflow: Script Filter (keyword `sf`) → Run Script → Alfred's notification, shown only with text."""
    version = json.loads((ROOT / "nsh.json").read_text(encoding="utf-8"))["version"]
    search, run, notify = "8E8C7B9A-5A1F-4E0B-9C4D-0A1B2C3D4E51", "8E8C7B9A-5A1F-4E0B-9C4D-0A1B2C3D4E52", "8E8C7B9A-5A1F-4E0B-9C4D-0A1B2C3D4E53"
    link = lambda to: [{"destinationuid": to, "modifiers": 0, "modifiersubtext": "", "vitoclose": False}]
    return {
        "bundleid": "com.gicek.safay.alfred",
        "category": "Tools",
        "version": version,
        "createdby": "Safay",
        "description": "Search Safay accounts and copy codes with a keyword",
        "disabled": False,
        "name": "Safay",
        "readme": (
            "Type `sf` and a service or account name. Enter asks Safay to copy that account's code: Safay asks for Touch ID "
            "or your master password every time, puts the code on the clipboard and shows a notice.\n\n"
            "Needs Safay's Settings → Advanced → Enable Third-Party Plugin Interface, and Alfred allowed to control Safay "
            "(System Settings → Privacy & Security → Automation)."
        ),
        "webaddress": "",
        "connections": {search: link(run), run: link(notify)},
        "objects": [
            {
                "type": "alfred.workflow.input.scriptfilter",
                "uid": search,
                "version": 3,
                "config": {
                    "keyword": "sf",
                    "title": "Safay",
                    "subtext": "Search Safay accounts",
                    "runningsubtext": "…",
                    # The query as argv ($1), never spliced into a script.
                    "script": '/usr/bin/osascript -l JavaScript ./search.js "$1"',
                    "scriptargtype": 1,
                    "type": 0,
                    "withspace": True,
                    "alfredfiltersresults": False,
                    "argumenttype": 1,
                    "queuemode": 1,
                    "queuedelaymode": 0,
                    "queuedelaycustom": 3,
                    "queuedelayimmediatelyinitially": True,
                },
            },
            {
                "type": "alfred.workflow.action.script",
                "uid": run,
                "version": 2,
                "config": {"script": '/usr/bin/osascript -l JavaScript ./copy.js "$1"', "scriptargtype": 1, "type": 0, "scriptfile": "", "concurrently": False},
            },
            {
                "type": "alfred.workflow.output.notification",
                "uid": notify,
                "version": 1,
                "config": {"argument": 0, "title": "Safay", "text": "{query}", "icon": "icon.png", "onlyshowifquerypopulated": True},
            },
        ],
        "uidata": {search: {"xpos": 170, "ypos": 90}, run: {"xpos": 430, "ypos": 90}, notify: {"xpos": 690, "ypos": 90}},
    }


def alfred(out: Path) -> None:
    source = ROOT / "integrations/alfred"
    info = alfred_info()
    marker = "@@SAFAY_STRINGS@@"
    files = {}
    for name in ["search.js", "copy.js"]:
        text = (source / name).read_text(encoding="utf-8")
        if marker in text:
            text = text.replace(marker, json.dumps(strings(), ensure_ascii=False))
        files[name] = text.encode()
    files["safay.applescript"] = BRIDGE.read_bytes()
    files["icon.png"] = (ROOT / "integrations/raycast/assets/icon.png").read_bytes()
    files["info.plist"] = plistlib.dumps(info, sort_keys=True)
    out.parent.mkdir(parents=True, exist_ok=True)
    # Deterministic: fixed order, fixed timestamps and modes.
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for name in sorted(files):
            entry = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            entry.external_attr = (0o755 if name.endswith(".js") else 0o644) << 16
            entry.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(entry, files[name])


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail when generated.ts is out of date")
    parser.add_argument("--alfred", type=Path, help="write Safay.alfredworkflow here")
    args = parser.parse_args()
    text = generated_ts()
    if args.check:
        if GENERATED.read_text(encoding="utf-8") != text:
            sys.exit("integrations/raycast/src/generated.ts is out of date: run python3 scripts/integrations.py")
    else:
        GENERATED.write_text(text, encoding="utf-8", newline="\n")
    if args.alfred:
        alfred(args.alfred)


if __name__ == "__main__":
    main()
